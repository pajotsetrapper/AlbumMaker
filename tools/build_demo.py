def demo_folder(template: str) -> Path:
    return DEMO if template == "classic" else ROOT / "docs" / f"demo-{template}"


def drop_fonts(site: Path) -> None:
    """The non-classic templates use system fonts: leave the font files out."""
    vendor = site / "assets" / "vendor"
    shutil.rmtree(vendor / "fonts", ignore_errors=True)
    for licence in (vendor / "licenses").glob("*"):
        if "leaflet" not in licence.name.lower():
            licence.unlink()
    versions = vendor / "VERSIONS.txt"
    if versions.is_file():
        kept = [line for line in versions.read_text(encoding="utf-8").splitlines()
                if not line.startswith("@fontsource")]
        text = "\n".join(kept).replace("Leaflet is BSD-2-Clause, the fonts are\nSIL Open Font License 1.1.",
                                       "Leaflet is BSD-2-Clause.")
        versions.write_text(text + "\n", encoding="utf-8")


def build_one(template: str, trip: Path, work: Path, config: Path) -> Path:
    site = work / f"site-{template}"
    env = dict(os.environ, ALBUMMAKER_CONFIG_DIR=str(config))
    subprocess.run([sys.executable, str(ROOT / "generate_site.py"), "-i", str(trip),
                    "-o", str(site), "--timezone", TIMEZONE,
                    "--large-thumb-size", "1600", "--template", template],
                   cwd=work, env=env, check=True)
    (site / ".trip_site_manifest.json").unlink(missing_ok=True)   # only needed to rebuild
    if template != "classic":
        drop_fonts(site)
        (site / "NOTICE.txt").write_text(
            NOTICE.format(template=template, rule="=" * (len(template) + 34)), encoding="utf-8")
    return site


def replace_folder(target: Path, site: Path) -> None:
    target.mkdir(exist_ok=True)
    for entry in target.iterdir():
        if entry.name in KEEP and target == DEMO:
            continue
        shutil.rmtree(entry) if entry.is_dir() else entry.unlink()
    for entry in site.iterdir():
        destination = target / entry.name
        shutil.copytree(entry, destination) if entry.is_dir() else shutil.copy2(entry, destination)


def main(argv=None) -> int:
    wanted = list(sys.argv[1:] if argv is None else argv) or template_names()
    unknown = [name for name in wanted if name not in template_names()]
    if unknown:
        print(f"Unknown template: {', '.join(unknown)}. Choose from: {', '.join(template_names())}.",
              file=sys.stderr)
        return 2
    photos = sorted((DEMO / "media").glob("*.jpg"))
    vendor = DEMO / "assets" / "vendor"
    if not photos or not (vendor / "VERSIONS.txt").is_file():
        print(f"Expected the sample photos in {DEMO / 'media'} and the offline assets in {vendor}.",
              file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory(prefix="albummaker-demo-") as temporary:
        work = Path(temporary)
        trip, config = work / "Lake Lucerne", work / "config"
        trip.mkdir()
        for photo in photos:
            shutil.copy2(photo, trip / photo.name)
        for name in ("trip_content.json", "lake-lucerne.gpx"):
            shutil.copy2(SOURCE / name, trip / name)
        # the builder copies offline assets from AlbumMaker's own folder
        shutil.copytree(vendor, config / "offline-assets")
        # build everything first, so a failed build leaves the folders as they were
        sites = {name: build_one(name, trip, work, config) for name in wanted}
        for name, site in sites.items():
            replace_folder(demo_folder(name), site)
            print(f"Sample trip ({name}) rebuilt in {demo_folder(name)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
